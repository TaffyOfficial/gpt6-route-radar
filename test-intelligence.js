const assert = require('assert/strict');
const R = require('./rank.js');
const row = (id, status, blacklist) => ({id, channelId:id,name:'channel '+id,source:'Codex Pro',model:'gpt-6-astra',multiplier:.2,groupRequests:100,verified:true,lifecycle:'active',modelStatus:'healthy',cache:80,ttftAvg:1000,ttftSamples:10,intelligence:{status,blacklist,qualityHistory:['normal','normal',status].map(outcome=>({outcome,at:new Date().toISOString()}))}});
const snapshot = {model:'gpt-6-astra',rows:[row('1','severe','temporary'),row('2','severe','permanent'),row('3','mild'),row('4','normal'),row('5')],complete:true,capturedAt:new Date().toISOString()};
const r = R.rank(snapshot);
assert.deepEqual(r.eligible.map(r=>r.id), ['4','5','3','1','2']);
assert.deepEqual(r.blocked, []);
assert.equal(r.rows.find(r=>r.id==='1').intelligenceFactor,.5);
assert.deepEqual(R.rank(snapshot,{blockedKeys:['channel:1']}).blocked.map(r=>r.id),['1']);
assert.equal(R.search(snapshot,r,'2').outside.length,0);
assert.equal(R.defaults.source,'Codex Pro');
assert.deepEqual(R.plan(snapshot).channels.map(r=>r.channel_id), ['4','5','3']);
console.log('PASS intelligence recommendation, search and export');

const mild = r.rows.find(x=>x.id==='3');
assert.ok(Math.abs(mild.score - mild.preIntelligenceScore * .8)<1e-9);
assert.ok(Math.abs(Object.values(mild.scoreContributions).reduce((a,b)=>a+b,0)-mild.score)<1e-9);
assert.equal(R.plan(snapshot).channels.find(x=>x.channel_id==='3').intelligenceFactor,.8);
const tool = R.rank({...snapshot, rows:[{...row('tool','normal'), intelligence:{toolUnavailable:true}}]}).rows[0];
assert.equal(tool.intelligenceFactor,.8);
const legacyTool = R.rank({...snapshot, rows:[{...row('legacy','normal'), intelligence:{lastError:{at:new Date().toISOString(),message:'无法调用工具'}}}]}).rows[0];
assert.equal(legacyTool.intelligenceFactor,.8);
const requestFailure = R.rank({...snapshot, rows:[{...row('request'), intelligence:{lastError:{at:new Date().toISOString(),message:'模型调用服务暂不可用（HTTP 503）'}}}]}).rows[0];
assert.equal(requestFailure.intelligenceFactor,.8);
assert.equal(R.intelligenceStability(requestFailure.intelligence).label,'检测请求失败 · 待复测');
const curve = R.rank({...snapshot,rows:[{...row('a'),multiplier:.1,cache:100},{...row('b'),multiplier:.2,cache:100},{...row('c'),multiplier:.4,cache:100}]}).rows;
assert.deepEqual(curve.map(x=>x.components.effective),[80,50,20]);
console.log('PASS smooth price anchors and quality discount consistency');

const reference = Date.parse('2026-10-05T16:00:00Z');
const event = (outcome, hours = 0) => ({outcome, at:new Date(reference - hours * 3600000).toISOString()});
const stability = events => R.intelligenceStability({qualityHistory:events}, reference);
assert.equal(stability([event('severe')]).factor,.5);
assert.equal(stability([event('mild')]).factor,.8);
assert.equal(stability([event('normal'),event('severe',23)]).factor,.5);
assert.equal(stability([event('error'),event('normal'),event('mild')]).factor,.8);
assert.equal(stability([event('normal'),event('mild'),event('severe')]).factor,.5);
assert.equal(stability([event('normal'),event('normal'),event('normal'),event('severe',23)]).factor,.5);
assert.equal(stability([event('severe',24),event('normal')]).factor,1);
assert.equal(stability([event('severe',25),event('mild',23)]).factor,.8);
assert.equal(stability([event('severe',-1),{outcome:'severe',at:'invalid'}]).factor,1);
assert.equal(stability([event('normal'),event('normal'),event('normal')]).factor,1);
assert.equal(stability([]).label,'近24小时无有效检测');
assert.equal(R.intelligenceStability({lastError:{at:event('error',25).at,message:'HTTP 503'}},reference).factor,1);
assert.equal(R.intelligenceStability({qualityHistory:[event('severe')],lastError:{at:event('error').at,message:'HTTP 503'}},reference).factor,.5);
const timeRow = {...row('time','normal'),intelligence:{status:'normal',qualityHistory:[event('severe',23)]}};
assert.equal(R.rank({...snapshot,rows:[timeRow]}, {}, reference).rows[0].intelligenceFactor,.5);
assert.equal(R.rank({...snapshot,rows:[timeRow]}, {}, reference + 3600000).rows[0].intelligenceFactor,1);
console.log('PASS rolling 24-hour quality window, expiry and ranking clock');
