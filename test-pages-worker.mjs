import assert from 'node:assert/strict';
import { gzipSync } from 'node:zlib';
import worker from './deploy/pages-worker.mjs';
const stored = new Map(), pending = []; let reads = 0;
globalThis.caches = { default: { match: async key => stored.get(key.url)?.clone(), put: async (key, value) => { stored.set(key.url, value); } } };
const context = { waitUntil: promise => pending.push(promise) };
const env = { SNAPSHOTS: { get: async key => { assert.equal(key, 'latest.json.gz'); reads++; return { body: new Blob([gzipSync('{"complete":true}')]).stream() }; } }, ASSETS: { fetch: async () => new Response('asset') } };
let response = await worker.fetch(new Request('https://route-radar.pages.dev/api/snapshot?random=1'), env, context);
assert.deepEqual(await response.json(), { complete: true });
await Promise.all(pending);
response = await worker.fetch(new Request('https://route-radar.pages.dev/api/snapshot?random=2'), env, context);
assert.deepEqual(await response.json(), { complete: true });
assert.equal(reads, 1);
assert.equal(response.headers.get('cache-control'), 'public, max-age=60');
response = await worker.fetch(new Request('https://route-radar.pages.dev/api/snapshot', { method: 'HEAD' }), env, context);
assert.equal(await response.text(), '');
assert.equal((await worker.fetch(new Request('https://route-radar.pages.dev/api/snapshot', { method: 'PUT' }), env, context)).status, 405);
assert.equal(await (await worker.fetch(new Request('https://route-radar.pages.dev/'), env, context)).text(), 'asset');
console.log('Pages internal R2 read, gzip decoding, shared cache and method restrictions passed');
